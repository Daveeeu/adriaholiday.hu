// Writes the pixel size of every user guide screenshot (public/guide-images/*.webp)
// to src/features/user-guide/lib/guide-image-sizes.ts. Run it after adding or
// replacing a screenshot: npm run user-guide:sizes
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const imageDir = path.join(root, 'public/guide-images');
const target = path.join(
  root,
  'src/features/user-guide/lib/guide-image-sizes.ts',
);

function webpSize(buffer) {
  const chunk = buffer.toString('ascii', 12, 16);

  if (chunk === 'VP8X') {
    return {
      width: 1 + buffer.readUIntLE(24, 3),
      height: 1 + buffer.readUIntLE(27, 3),
    };
  }

  if (chunk === 'VP8L') {
    const bits = buffer.readUInt32LE(21);
    return { width: 1 + (bits & 0x3fff), height: 1 + ((bits >> 14) & 0x3fff) };
  }

  if (chunk === 'VP8 ') {
    return {
      width: buffer.readUInt16LE(26) & 0x3fff,
      height: buffer.readUInt16LE(28) & 0x3fff,
    };
  }

  throw new Error(`Unsupported WebP chunk: ${chunk}`);
}

const entries = readdirSync(imageDir)
  .filter((file) => file.endsWith('.webp'))
  .sort()
  .map((file) => {
    const { width, height } = webpSize(readFileSync(path.join(imageDir, file)));
    return `  '${file.replace(/\.webp$/, '')}': { width: ${width}, height: ${height} },`;
  });

writeFileSync(
  target,
  `// Generated by scripts/generate-user-guide-image-sizes.mjs – do not edit by hand.
export const GUIDE_IMAGE_SIZES: Record<string, { width: number; height: number }> = {
${entries.join('\n')}
};
`,
);

// Keep the generated file in the project's formatting.
execFileSync('npx', ['prettier', '--write', target], { cwd: root });

console.log(
  `Wrote ${entries.length} image sizes to ${path.relative(root, target)}`,
);
